package com.pocketdesk.app.transport.hid

/**
 * HID report descriptors, reused verbatim from two MIT-licensed projects.
 *
 * Both are composite "keyboard + mouse + consumer" descriptors sharing one
 * Bluetooth HID connection, distinguished by Report ID. They differ in ways that
 * matter when a host refuses the device:
 *
 *  - [A_LINKPAD]  : keyboard is Report ID 1 (the "boot keyboard first" layout used
 *    by a commercial APK, byte-exact from Linkpad, MIT © 2026 Devdas Kumar),
 *    5 mouse buttons, 8-bit relative X/Y, AC Pan horizontal scroll.
 *  - [B_BECKON]   : mouse is Report ID 1 with 16-bit relative X/Y (no clipping on
 *    fast flicks), 3 buttons, no horizontal pan. Descriptor from Beckon, MIT © 2026 Om Singh.
 *
 * Keeping both lets us A/B the exact report layout against a picky host such as a
 * ColorOS tablet *without* rewriting code — one setting, then re-pair.
 */
data class HidProfile(
    val id: String,
    val label: String,
    val note: String,
    val descriptor: ByteArray,
    val keyboardReportId: Int,
    val mouseReportId: Int,
    val consumerReportId: Int,
    val mouseReportSize: Int,
    val keyboardReportSize: Int,
    val consumerReportSize: Int,
    val mouseButtonCount: Int,
    val widePointer: Boolean,
    val hasHorizontalScroll: Boolean,
) {
    // Data class with a ByteArray: identity equality on id is what we actually want.
    override fun equals(other: Any?): Boolean = other is HidProfile && other.id == id
    override fun hashCode(): Int = id.hashCode()
}

